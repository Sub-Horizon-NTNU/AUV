param(
    [ValidateSet('Setup', 'Configure', 'Build', 'Test', 'Run', 'Scan', 'Debug', 'View')]
    [string]$Action = 'Build'
)

$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$buildRoot = Join-Path $projectRoot 'build-vscode'
$outputRoot = Join-Path $projectRoot 'output'
$generatedHeader = '// Generated by scripts/dev.ps1 (sonar-vscode-v1).'
$script:failureExitCode = 1

function Find-Tool([string]$Name, [string]$BundledPath) {
    $command = Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($command) { return $command.Source }
    foreach ($installation in $clionInstallations) {
        $candidate = Join-Path $installation.FullName $BundledPath
        if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
    }
    throw "Cannot find $Name. Install CMake, Ninja and MinGW (GCC/GDB), or CLion's bundled tools, then rerun Setup."
}

function Invoke-Checked([string]$Executable, [string[]]$Arguments) {
    & $Executable @Arguments
    if ($LASTEXITCODE -ne 0) {
        $script:failureExitCode = $LASTEXITCODE
        throw "$([IO.Path]::GetFileName($Executable)) failed with exit code $LASTEXITCODE."
    }
}

function Read-GeneratedJson([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return [pscustomobject]@{} }
    $content = [IO.File]::ReadAllText($Path)
    if (-not $content.StartsWith($generatedHeader, [StringComparison]::Ordinal)) {
        throw "Preserved existing $Path because it is not managed by this script. Back it up and remove it before Setup."
    }
    return ($content.Substring($generatedHeader.Length) | ConvertFrom-Json)
}

function Merge-Fields($Target, [System.Collections.IDictionary]$Fields) {
    foreach ($key in $Fields.Keys) {
        $value = $Fields[$key]
        if ($value -is [System.Collections.IDictionary]) {
            $nested = $Target.PSObject.Properties[$key]
            $child = if ($nested -and $nested.Value -is [pscustomobject]) {
                $nested.Value
            } else { [pscustomobject]@{} }
            Merge-Fields $child $value
            $value = $child
        }
        $Target | Add-Member -NotePropertyName $key -NotePropertyValue $value -Force
    }
}

function Write-GeneratedJson([string]$Path, $Value) {
    $json = $Value | ConvertTo-Json -Depth 12
    [IO.File]::WriteAllText($Path, "$generatedHeader`r`n$json`r`n", (New-Object Text.UTF8Encoding($false)))
}

function Write-EditorConfiguration {
    $editorRoot = Join-Path $projectRoot '.vscode'
    $settingsPath = Join-Path $editorRoot 'settings.json'
    $launchPath = Join-Path $editorRoot 'launch.json'
    # Read both before writing either; unknown existing configurations remain intact.
    $settings = Read-GeneratedJson $settingsPath
    $launch = Read-GeneratedJson $launchPath
    $editorPath = "$toolPath;`${env:PATH}"
    Merge-Fields $settings ([ordered]@{
        'cmake.cmakePath' = $tools.CMake
        'cmake.generator' = 'Ninja'
        'cmake.configureOnOpen' = $false
        'cmake.sourceDirectory' = '${workspaceFolder}'
        'cmake.buildDirectory' = '${workspaceFolder}/build-vscode'
        'cmake.configureSettings' = [ordered]@{
            'CMAKE_CXX_COMPILER' = $tools.Compiler
            'CMAKE_MAKE_PROGRAM' = $tools.Ninja
            'CMAKE_BUILD_TYPE' = 'Debug'
            'CMAKE_EXPORT_COMPILE_COMMANDS' = $true
        }
        'cmake.environment' = @{ 'PATH' = $editorPath }
        'C_Cpp.default.compilerPath' = $tools.Compiler
        'C_Cpp.default.cppStandard' = 'c++17'
        'C_Cpp.default.intelliSenseMode' = 'windows-gcc-x64'
        'C_Cpp.default.compileCommands' = '${workspaceFolder}/build-vscode/compile_commands.json'
        'terminal.integrated.env.windows' = @{ 'PATH' = $editorPath }
    })
    $debugName = 'Sonar: Debug simulator'
    $otherConfigurations = @($launch.configurations | Where-Object { $null -ne $_ -and $_.name -ne $debugName })
    $configuration = [ordered]@{
        'name' = $debugName
        'type' = 'cppdbg'
        'request' = 'launch'
        'program' = '${workspaceFolder}/build-vscode/sonar_sim.exe'
        'args' = @('--config', '${workspaceFolder}/examples/pool.cfg', '--output', '${workspaceFolder}/output/debug-current')
        'cwd' = '${workspaceFolder}'
        'stopAtEntry' = $false
        'externalConsole' = $false
        'MIMode' = 'gdb'
        'miDebuggerPath' = $tools.Debugger
        'environment' = @(@{ 'name' = 'PATH'; 'value' = $editorPath })
        'preLaunchTask' = 'Sonar: Prepare debug'
        'setupCommands' = @(@{ 'text' = '-enable-pretty-printing'; 'ignoreFailures' = $true })
    }
    Merge-Fields $launch @{ 'version' = '0.2.0'; 'configurations' = @($otherConfigurations) + @($configuration) }
    [IO.Directory]::CreateDirectory($editorRoot) | Out-Null
    Write-GeneratedJson $settingsPath $settings
    Write-GeneratedJson $launchPath $launch
    Write-Host "Generated local VS Code settings and F5 configuration in $editorRoot"
}

function Assert-OutputPath([string]$Path) {
    $absolute = [IO.Path]::GetFullPath($Path)
    $prefix = [IO.Path]::GetFullPath($outputRoot).TrimEnd('\') + '\'
    if (-not $absolute.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing an operation outside the project output directory: $absolute"
    }
    if (Test-Path -LiteralPath $absolute) {
        if ((Get-Item -LiteralPath $absolute -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
            throw "Refusing to manage a reparse point: $absolute"
        }
    }
    return $absolute
}

function Prepare-DebugOutput {
    if ((Get-Item -LiteralPath $outputRoot -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Refusing to manage a reparse point: $outputRoot"
    }
    $current = Assert-OutputPath (Join-Path $outputRoot 'debug-current')
    if (Test-Path -LiteralPath $current) {
        $history = Assert-OutputPath (Join-Path $outputRoot 'debug-history')
        [IO.Directory]::CreateDirectory($history) | Out-Null
        $destination = Assert-OutputPath (Join-Path $history (New-RunName 'debug'))
        Move-Item -LiteralPath $current -Destination $destination
        Write-Host "Previous debug output preserved in $destination"
    }
    Write-Host "Debug output: $current"
}

function New-RunName([string]$Prefix) {
    return "$Prefix-$(Get-Date -Format 'yyyyMMdd-HHmmss-fff')-$([Guid]::NewGuid().ToString('N').Substring(0, 8))"
}

try {
    $installationRoots = @("$env:ProgramFiles\JetBrains", "$env:LOCALAPPDATA\Programs")
    $clionInstallations = @($installationRoots | Where-Object { Test-Path -LiteralPath $_ } |
        ForEach-Object { Get-ChildItem -LiteralPath $_ -Directory -Filter 'CLion*' } |
        Sort-Object Name -Descending)
    $tools = [ordered]@{
        Compiler = Find-Tool 'g++.exe' 'bin\mingw\bin\g++.exe'
        CMake = Find-Tool 'cmake.exe' 'bin\cmake\win\x64\bin\cmake.exe'
        Ninja = Find-Tool 'ninja.exe' 'bin\ninja\win\x64\ninja.exe'
        CTest = Find-Tool 'ctest.exe' 'bin\cmake\win\x64\bin\ctest.exe'
        Debugger = Find-Tool 'gdb.exe' 'bin\gdb\win\x64\bin\gdb.exe'
    }
    $toolPath = ($tools.Values | ForEach-Object { Split-Path -Parent $_ } | Select-Object -Unique) -join ';'
    $env:PATH = "$toolPath;$env:PATH"
    if ($Action -eq 'Setup') {
        Write-EditorConfiguration
        $tools.GetEnumerator() | ForEach-Object { Write-Host "$($_.Key): $($_.Value)" }
        exit 0
    }
    $configureArguments = @('-S', $projectRoot, '-B', $buildRoot, '-G', 'Ninja',
        "-DCMAKE_CXX_COMPILER=$($tools.Compiler)", "-DCMAKE_MAKE_PROGRAM=$($tools.Ninja)",
        '-DCMAKE_BUILD_TYPE=Debug', '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON')
    if ($Action -eq 'View') {
        $configureArguments += @('-DSONAR_BUILD_VIEWER=ON', "-DCMAKE_C_COMPILER=$(Join-Path (Split-Path $tools.Compiler -Parent) 'gcc.exe')")
    } else {
        $configureArguments += '-DSONAR_BUILD_VIEWER=OFF'
    }
    Invoke-Checked $tools.CMake $configureArguments
    if ($Action -eq 'Configure') { exit 0 }
    Invoke-Checked $tools.CMake @('--build', $buildRoot)
    if ($Action -eq 'View') {
        Push-Location $projectRoot
        try {
            Invoke-Checked (Join-Path $buildRoot 'sonar_viewer.exe') @('--config', (Join-Path $projectRoot 'examples\pool.cfg'))
        } finally { Pop-Location }
    } elseif ($Action -eq 'Test') {
        Invoke-Checked $tools.CTest @('--test-dir', $buildRoot, '--output-on-failure')
    } elseif ($Action -eq 'Debug') {
        [IO.Directory]::CreateDirectory($outputRoot) | Out-Null
        Prepare-DebugOutput
    } elseif ($Action -eq 'Run' -or $Action -eq 'Scan') {
        $prefix = if ($Action -eq 'Scan') { 'scan' } else { 'ping' }
        $destination = Join-Path $outputRoot (New-RunName $prefix)
        $arguments = @('--config', (Join-Path $projectRoot 'examples\pool.cfg'), '--output', $destination)
        if ($Action -eq 'Scan') { $arguments += '--scan' }
        Invoke-Checked (Join-Path $buildRoot 'sonar_sim.exe') $arguments
    }
} catch {
    Write-Error "Sonar $Action failed: $($_.Exception.Message)" -ErrorAction Continue
    exit $script:failureExitCode
}
